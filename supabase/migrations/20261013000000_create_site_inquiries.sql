-- Persistent public contact enquiries. Apply in Supabase SQL Editor or via migrations.
create table if not exists public.site_inquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  subject text not null,
  message text not null,
  status text not null default 'new' check (status in ('new', 'read', 'resolved')),
  created_at timestamptz not null default now()
);
alter table public.site_inquiries enable row level security;
-- No public policies: inserts/reads are performed by trusted server functions using service-role credentials.
create index if not exists site_inquiries_created_at_idx on public.site_inquiries (created_at desc);
